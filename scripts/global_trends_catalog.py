def resolve_source_status(src: Dict[str, Any]) -> str:
    """Return status: Connected, Available, or Setup Required."""
    if src.get("requires_auth"):
        env_var = src.get("auth_env_var")
        if env_var and not os.getenv(env_var, "").strip():
            return "Setup Required"
        return "Connected"
    return "Available"

def get_all_trend_sources() -> List[Dict[str, Any]]:
    """Return complete sources catalog with live connection status."""
    results = []
    for item in GLOBAL_SOURCES:
        entry = dict(item)
        entry["status"] = resolve_source_status(item)
        results.append(entry)
    return results

